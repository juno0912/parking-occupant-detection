#!/usr/bin/env bash
# =============================================================================
# setup_rdp.sh
#   Raspberry Pi 4B (Raspberry Pi OS / Debian 13 trixie) 에서
#   Windows "원격 데스크톱 연결"(mstsc)로 접속할 수 있도록 xrdp 를 구성한다.
#
#   - SD 카드 재설치 없이 기존 OS 위에 패키지만 추가한다.
#   - 평소에는 콘솔(CLI)로 부팅하고, mstsc 로 접속할 때만 GUI 세션이 열린다.
#   - RDP 세션 전용 시작 파일(~/startwm.sh)을 쓰므로 Pi 로컬 데스크톱은 건드리지 않는다.
#   - VNC 는 건드리지 않는다. mstsc 접속을 직접 확인한 뒤 --purge-vnc 로 따로 제거한다.
#   - RDP 세션 안에서 CSI 카메라 미리보기(rpicam-hello --qt-preview,
#     picamera2 Preview.QT, cv2.imshow)를 쓸 수 있게 한다.
#   - 여러 대에 반복 실행해도 안전하도록(idempotent) 작성했다.
#     설치 전에 시뮬레이션으로 확인해서, 라이브러리 교체 외에 기존 패키지를 지우는 설치는 하지 않는다.
#
# 사용법 (Pi 에서 일반 사용자로 실행, sudo 비밀번호는 처음에 한 번 묻는다)
#   bash setup_rdp.sh             # 설치 및 구성
#   bash setup_rdp.sh --check     # 현재 상태만 점검 (변경 없음, 로그 없음)
#   bash setup_rdp.sh --rollback  # 이 스크립트가 바꾼 것 되돌리기
#   bash setup_rdp.sh --fix-logout # 패널 Logout 오류만 고치기 (이미 설치한 Pi 용)
#   bash setup_rdp.sh --purge-vnc  # mstsc 접속을 확인한 뒤 VNC 서버 제거 (기본 설치는 VNC 를 건드리지 않음)
# =============================================================================
set -Eeuo pipefail

MODE="${1:-install}"
TARGET_USER="$(id -un)"
TARGET_HOME="$(getent passwd "$TARGET_USER" | cut -d: -f6)"
STATE_DIR="/var/lib/setup_rdp"
LOG="$TARGET_HOME/setup_rdp_$(date +%Y%m%d_%H%M%S).log"
MARK="generated by setup_rdp.sh"

PKGS_RDP=(xrdp xorgxrdp ssl-cert)
# Raspberry Pi 공식 X11 데스크톱 (메뉴/앱 목록/시계/로그아웃 포함). 실행: /usr/bin/startx-rpd
PKGS_RPD=(rpd-x-core)
# Pi 데스크톱 구성 (없으면 건너뜀)
#  - rpd-theme       : 공식 테마/아이콘/배경화면
#  - rpd-preferences : Raspberry Pi 설정, 외관 설정, 프린터 등 설정 앱
#  - 테마/로더 개별 이름도 함께 지정: 이미 rpd-x-core 가 설치된 Pi 는 권장 패키지가 다시 설치되지 않으므로
#    (이미지 로더가 없으면 "Could not load a pixbuf from icon theme" 로 아이콘/배경/작업표시줄이 안 그려짐)
PKGS_RPD_OPTIONAL=(rpd-theme rpd-preferences
                   pixtrix-theme pixtrix-icons fonts-nunito-sans fonts-liberation2 rpd-wallpaper rpd-wallpaper-trixie
                   libgdk-pixbuf2.0-bin librsvg2-common shared-mime-info at-spi2-core
                   x11-utils)   # x11-utils: 화면 진단(xwininfo)용
# rpd-x-core 를 쓸 수 없을 때의 경량 대체 데스크톱
PKGS_DESKTOP_BASE=(openbox lxterminal x11-xserver-utils dbus-bin)
DESKTOP_MODE=""  # rpd 또는 light (choose_desktop 에서 결정)
# 폰트/카메라/파이썬: 롤백해도 남겨 둔다
PKGS_EXTRA=(fonts-nanum rpicam-apps python3-picamera2 python3-pyqt5 python3-opencv python3-numpy)
# 기본 데스크톱 앱 (Pi 공식 저장소). 없으면 건너뛰고, 롤백해도 남겨 둔다
#  브라우저(+Pi 용 설정), VS Code, 터미널, 텍스트 편집기, 작업 관리자, 계산기, 이미지 뷰어, 압축 관리자
PKGS_APPS=(chromium rpi-chromium-mods firefox rpi-firefox-mods code
           lxterminal mousepad lxtask galculator eom xarchiver)
PKGS_KEEP=("${PKGS_EXTRA[@]}" "${PKGS_APPS[@]}" dbus-bin)
PANEL_PKG=""   # lxpanel-pi 또는 lxpanel (choose_desktop 에서 결정)
FM_PKG=""      # pcmanfm-pi 또는 pcmanfm

c_ok=$'\e[32m'; c_warn=$'\e[33m'; c_err=$'\e[31m'; c_off=$'\e[0m'
log()  { printf '%s\n' "$*"; }
step() { printf '\n%s==> %s%s\n' "$c_ok" "$*" "$c_off"; }
warn() { printf '%s[경고] %s%s\n' "$c_warn" "$*" "$c_off" >&2; }
die()  { printf '%s[오류] %s%s\n' "$c_err" "$*" "$c_off" >&2; [[ "$MODE" == install || "$MODE" == --rollback ]] && printf '로그: %s\n' "$LOG" >&2; exit 1; }

SUDO_KEEPALIVE=""
cleanup() { [[ -n "$SUDO_KEEPALIVE" ]] && kill "$SUDO_KEEPALIVE" 2>/dev/null; return 0; }
trap cleanup EXIT
trap 'printf "%s[오류] %s번째 줄에서 실패: %s%s\n" "$c_err" "$LINENO" "$BASH_COMMAND" "$c_off" >&2' ERR

# 주의: set -o pipefail 상태에서 "명령 | grep -q" 를 쓰면 grep 이 먼저 끝나
#       앞 명령이 SIGPIPE(141)로 죽고 파이프 전체가 실패로 판정될 수 있다.
#       그래서 출력을 변수에 먼저 담은 뒤 비교한다. (LC_ALL=C 로 영문 출력 고정)
is_installed() {
  local s
  s="$(LC_ALL=C dpkg-query -W -f='${Status}' "$1" 2>/dev/null || true)"
  [[ "$s" == "install ok installed" ]]
}
pkg_available() {
  local out re='Candidate: [^(]'
  out="$(LC_ALL=C apt-cache policy "$1" 2>/dev/null || true)"
  [[ "$out" =~ $re ]]
}
in_list() { local x="$1"; shift; local y; for y in "$@"; do [[ "$x" == "$y" ]] && return 0; done; return 1; }
state_get() { [[ -f "$STATE_DIR/$1" ]] && cat "$STATE_DIR/$1" || true; }
state_set_once() { [[ -f "$STATE_DIR/$1" ]] || printf '%s\n' "$2" | sudo tee "$STATE_DIR/$1" >/dev/null; }

# 지정한 패키지만 지워지는 경우에만 purge 한다. (다른 패키지가 딸려 지워지면 건너뜀)
safe_purge() {
  local plan extra
  if ! plan="$(LC_ALL=C apt-get -s purge "$@" 2>&1)"; then
    warn "제거 계획 조회 실패, 제거를 건너뜁니다: $*"
    log "$plan"
    return 1
  fi
  extra="$(awk '/^(Purg|Remv) /{print $2}' <<<"$plan" | grep -vxF -f <(printf '%s\n' "$@") || true)"
  if [[ -n "$extra" ]]; then
    warn "다음 패키지도 함께 지워지므로 제거를 건너뜁니다: $(tr '\n' ' ' <<<"$extra")"
    return 1
  fi
  sudo DEBIAN_FRONTEND=noninteractive apt-get purge -y "$@"
}

# INI 형식 파일의 [section] key=value 를 설정한다. (없으면 섹션/키를 추가, 있으면 값만 교체)
set_ini_key() {
  local f="$1" sec="$2" key="$3" val="$4" tmp
  mkdir -p "${f%/*}"
  [[ -f "$f" ]] || : > "$f"
  tmp="$(mktemp "$f.tmp.XXXXXX")"
  awk -v sec="$sec" -v key="$key" -v val="$val" '
    function out() { print key "=" val; done = 1 }
    BEGIN { insec = 0; done = 0 }
    /^\[/ { if (insec && !done) out()
            h = $0; sub(/[[:space:]]+$/, "", h); insec = (h == "[" sec "]") }
    insec && index($0, "=") { k = substr($0, 1, index($0, "=") - 1); gsub(/[[:space:]]/, "", k)
                              if (k == key) { if (!done) out(); next } }
    { print }
    END { if (!done) { if (!insec) print "[" sec "]"; out() } }
  ' "$f" > "$tmp"
  mv -f "$tmp" "$f"
}

# 이 스크립트가 만든 파일(MARK 포함)이거나 아직 없을 때만 stdin 내용으로 쓴다.
write_if_ours() {
  local f="$1"
  if [[ -e "$f" ]] && ! grep -q "$MARK" "$f"; then
    warn "$f 가 이미 있어 건드리지 않습니다"
    cat > /dev/null
    return 1
  fi
  mkdir -p "${f%/*}" || die "디렉터리 생성 실패: ${f%/*}"
  cat > "$f" || die "파일 쓰기 실패: $f"
}

# 설치 전에 시뮬레이션으로 제거될 패키지를 확인한다.
#  - lib* 패키지만 제거되는 경우: 새 버전 라이브러리로 교체되는 것(예: libcamera0.7 → libcamera0.8)이라 허용
#  - 그 밖의 패키지(데스크톱, 앱 등)가 제거되는 경우: 설치하지 않고 중단
apt_install_safe() {
  local plan removes p bad=()
  # 권장(Recommends) 패키지까지 설치한다. Pi 데스크톱 묶음(rpd-theme, rpd-preferences 등)은
  # 내용물이 전부 Recommends 라서, 빼면 이름만 설치되고 아이콘/로더/설정 앱이 빠진다.
  if ! plan="$(LC_ALL=C apt-get -s install -y "$@" 2>&1)"; then
    log "$plan"
    die "설치 계획 조회 실패 (위 apt 메시지 확인)"
  fi
  removes="$(awk '/^Remv /{print $2}' <<<"$plan")"
  # 같은 이름의 새 버전 라이브러리가 함께 설치될 때만 "교체"로 인정한다.
  #   예) Remv libcamera0.7 + Inst libcamera0.8 → 둘 다 이름 뼈대가 libcamera
  local insts base; insts="$(awk '/^Inst /{print $2}' <<<"$plan" | sed -E 's/[0-9.]+(t64)?$//' | sort -u)"
  while IFS= read -r p; do
    [[ -z "$p" ]] && continue
    base="$(sed -E 's/[0-9.]+(t64)?$//' <<<"$p")"
    if [[ "$p" == lib* && "$base" != "$p" ]] && grep -qxF "$base" <<<"$insts"; then continue; fi
    bad+=("$p")
  done <<<"$removes"
  if (( ${#bad[@]} )); then
    die "설치하려면 다음 패키지를 지워야 해서 중단합니다: ${bad[*]}"
  fi
  if [[ -n "$removes" ]]; then
    log "새 버전으로 교체되어 제거되는 라이브러리(정상): $(tr '\n' ' ' <<<"$removes")"
  fi
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y "$@" \
    || die "패키지 설치 실패 (위 apt 메시지 확인)"
}

