check() {
  step "상태 점검"
  local rc=0

  if systemctl is-active --quiet xrdp; then log "[OK] xrdp 실행 중"; else warn "xrdp 가 실행 중이 아닙니다"; rc=1; fi
  if systemctl is-active --quiet xrdp-sesman; then log "[OK] xrdp-sesman 실행 중"; else warn "xrdp-sesman 이 실행 중이 아닙니다"; rc=1; fi
  if port_listening 3389; then log "[OK] 3389 포트(RDP) 대기 중"; else warn "3389 포트가 열려 있지 않습니다"; rc=1; fi
  if port_listening 5900; then log "[참고] VNC(5900)가 켜져 있습니다. mstsc 접속을 확인한 뒤 필요하면 --purge-vnc 로 제거"; else log "[OK] VNC(5900) 꺼짐"; fi

  local xs; xs="$TARGET_HOME/$(user_wm_file)"
  if [[ -x "$xs" ]] && grep -q "$MARK" "$xs"; then log "[OK] RDP 시작 파일: $xs"; else warn "RDP 시작 파일이 없거나 이 스크립트가 만든 것이 아닙니다: $xs"; rc=1; fi
  log "기본 부팅 대상: $(systemctl get-default)  (multi-user.target = 콘솔 부팅)"
  if [[ -x /usr/bin/startx-rpd ]]; then
    log "[OK] RDP 데스크톱: Raspberry Pi Desktop (X11)"
  else
    warn "RDP 데스크톱: 경량 모드 (공식 데스크톱 startx-rpd 없음)"
  fi
  # 아이콘/배경 이미지 로더 목록 (없으면 작업표시줄·바탕화면이 비어 보임)
  local lc
  lc="$(compgen -G '/usr/lib/*/gdk-pixbuf-2.0/2.10.0/loaders.cache' | head -n 1 || true)"
  if [[ -n "$lc" && -s "$lc" ]] && grep -q 'svg' "$lc"; then
    log "[OK] 이미지 로더(PNG/SVG) 등록됨"
  else
    warn "이미지 로더가 없거나 SVG 로더가 빠져 있습니다 (아이콘/작업표시줄이 안 보일 수 있음): sudo apt install libgdk-pixbuf2.0-bin librsvg2-common"
  fi

  # 로컬(모니터) 그래픽 세션만 확인한다. xrdp 세션은 seat 이 없으므로 제외된다.
  local s seat stype sessions
  sessions="$(loginctl list-sessions --no-legend 2>/dev/null | awk -v u="$TARGET_USER" '$3==u {print $1}' || true)"
  for s in $sessions; do
    seat="$(loginctl show-session "$s" -p Seat --value 2>/dev/null || true)"
    stype="$(loginctl show-session "$s" -p Type --value 2>/dev/null || true)"
    if [[ -n "$seat" && ( "$stype" == x11 || "$stype" == wayland ) ]]; then
      warn "$TARGET_USER 의 로컬(모니터) 그래픽 세션이 실행 중입니다. 같은 계정 RDP 는 검은 화면이 될 수 있으니 재부팅하세요."
      break
    fi
  done

  if command -v rpicam-hello >/dev/null; then
    log "--- 카메라 ---"
    local cams
    if cams="$(timeout 20 rpicam-hello --list-cameras 2>&1)"; then
      if grep -qi "no cameras" <<<"$cams"; then
        warn "카메라가 감지되지 않았습니다 (케이블/커넥터 확인). RDP 자체에는 영향 없음"
      else
        sed -n '1,8p' <<<"$cams"
      fi
    else
      warn "카메라 열거 실패 (다른 프로세스가 카메라 사용 중인지 확인)"
    fi
  else
    warn "rpicam-hello 가 없습니다"
  fi

  if python3 -c 'import picamera2, cv2' 2>/dev/null; then
    log "[OK] python3 에서 picamera2, cv2 import 가능 (미리보기 창은 RDP 접속 후 직접 확인)"
  else
    warn "python3 에서 picamera2 또는 cv2 import 실패"
  fi

  log "접속 주소: $(hostname -I | awk '{print $1}')"
  return "$rc"
}

