# 이전 버전 스크립트로 설치한 Pi 를 현재 방식으로 옮긴다.
#  - 이전 버전은 ~/.xsession 을 썼다 → 로컬 X11 로그인까지 바꾸므로 삭제 (지금은 ~/startwm.sh)
#  - 이전 버전은 Debian lxpanel/pcmanfm 을 설치했다 → Pi 전용 패키지로 교체
migrate_legacy() {
  step "이전 버전 설치 흔적 정리"
  local found=0 p old=()

  local oldxs="$TARGET_HOME/.xsession"
  if [[ -f "$oldxs" && ! -L "$oldxs" ]] && grep -q "$MARK" "$oldxs"; then
    rm -f "$oldxs"
    log "삭제(이전 버전 세션 파일): $oldxs"
    found=1
  fi

  for p in lxpanel pcmanfm; do
    if is_installed "$p" && grep -qxF "$p" "$STATE_DIR/installed_pkgs" 2>/dev/null \
       && { is_installed "$p-pi" || pkg_available "$p-pi"; }; then
      old+=("$p")
    fi
  done
  if (( ${#old[@]} )); then
    log "Pi 전용 패키지로 바꾸기 위해 제거: ${old[*]}"
    safe_purge "${old[@]}" || warn "제거하지 못해 이전 패키지를 계속 사용합니다: ${old[*]}"
    found=1
  fi

  # 이전 경량 모드(Debian pcmanfm)가 남긴 바탕화면 설정: "단색 검정 배경"이라
  # Pi 공식 배경(/etc/xdg/pcmanfm/default)을 덮어써서 화면이 검게 나온다. 백업 후 치운다.
  local c
  for c in "$TARGET_HOME"/.config/pcmanfm/*/desktop-items-*.conf; do
    [[ -f "$c" ]] || continue
    if grep -qx 'wallpaper_mode=color' "$c" && grep -qix 'desktop_bg=#000000' "$c"; then
      mv "$c" "$c.bak.$(date +%Y%m%d_%H%M%S)"
      log "검은 단색 바탕화면 설정을 백업 후 제거(공식 배경 사용): $c"
      found=1
    fi
  done

  (( found )) || log "정리할 이전 버전 흔적 없음"
  return 0
}

