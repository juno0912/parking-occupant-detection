# RDP 데스크톱 사용자 설정 (일반 사용자 권한, 홈 디렉터리 안에서만 변경)
configure_user_desktop() {
  step "RDP 데스크톱 사용자 설정 (검은 창 방지, 바탕화면 앱)"
  local bin="$TARGET_HOME/.local/bin" ad="$TARGET_HOME/.config/autostart"

  # 1) 화면 합성기(xcompmgr): xrdp 에서 창/화면이 검게 보이는 원인이 되므로 RDP 세션에서만 끈다.
  #    Pi 모니터로 로그인할 때는 원래대로 켜진다.
  if [[ -f /etc/xdg/autostart/xcompmgr.desktop ]]; then
    write_if_ours "$bin/rdp-xcompmgr" <<EOF && chmod 755 "$bin/rdp-xcompmgr"
#!/bin/sh
# $MARK : RDP 세션에서는 화면 합성기를 켜지 않는다
[ -n "\$RDP_SESSION_SETUP" ] && exit 0
exec /usr/bin/cmstart
EOF
    write_if_ours "$ad/xcompmgr.desktop" <<EOF && log "RDP 세션에서 화면 합성기(xcompmgr) 끔"
[Desktop Entry]
Type=Application
Name=xcompmgr
Comment=$MARK
NoDisplay=true
Exec=$bin/rdp-xcompmgr
EOF
  fi

  # 2) 작업표시줄: xrdp 화면 정보가 늦게 준비되면 패널이 보이지 않을 수 있어, RDP 세션에서만 잠시 후 다시 띄운다.
  write_if_ours "$bin/rdp-panel-fix" <<EOF && chmod 755 "$bin/rdp-panel-fix"
#!/bin/sh
# $MARK : RDP 세션에서 화면(모니터) 정보가 준비된 뒤 작업표시줄을 한 번 다시 시작한다
[ -n "\$RDP_SESSION_SETUP" ] || exit 0
i=0
while [ \$i -lt 15 ]; do
  case "\$(xrandr --listmonitors 2>/dev/null | head -n 1)" in
    *"Monitors: "[1-9]*) break ;;
  esac
  i=\$((i + 1)); sleep 1
done
sleep 2
if command -v lxpanelctl-pi >/dev/null 2>&1; then exec lxpanelctl-pi restart; fi
EOF
  write_if_ours "$ad/rdp-panel-fix.desktop" <<EOF && log "RDP 접속 후 작업표시줄 재시작 항목 추가"
[Desktop Entry]
Type=Application
Name=RDP panel fix
Comment=$MARK
NoDisplay=true
Exec=$bin/rdp-panel-fix
EOF

  # 3) 바탕화면 바로가기: Chromium, Firefox, VS Code, 터미널, 텍스트 편집기(Mousepad)
  local desk="$TARGET_HOME/Desktop" name src added=()
  mkdir -p "$desk"
  for name in chromium firefox com.microsoft.VSCode lxterminal org.xfce.mousepad mousepad; do
    src="/usr/share/applications/$name.desktop"
    [[ -f "$src" ]] || continue
    if [[ ! -e "$desk/$name.desktop" ]]; then
      cp "$src" "$desk/$name.desktop"
      chmod 755 "$desk/$name.desktop"
      added+=("$name")
    fi
  done
  if (( ${#added[@]} )); then log "바탕화면 바로가기 추가: ${added[*]}"; else log "바탕화면 바로가기: 추가할 것 없음"; fi
  # 바로가기를 열 때마다 "실행할까요?" 창이 뜨지 않게 한다 (실행 권한 있는 파일은 바로 실행됨)
  # 롤백 때 되돌릴 수 있도록 원래 값을 기록한다
  local libfm="$TARGET_HOME/.config/libfm/libfm.conf" prev
  if [[ "$MODE" == install && -d "$STATE_DIR" ]]; then
    prev="$(awk -F= '/^[[:space:]]*quick_exec[[:space:]]*=/{gsub(/[[:space:]]/,"",$2); print $2; exit}' "$libfm" 2>/dev/null || true)"
    state_set_once quick_exec_prev "${prev:-unset}"
  fi
  set_ini_key "$libfm" config quick_exec 1

  # 4) VS Code: Pi 4 와 RDP 에서는 GPU 가속을 꺼야 화면이 정상으로 그려진다 (VS Code 공식 안내 방식)
  if command -v code >/dev/null; then
    local argv="$TARGET_HOME/.vscode/argv.json"
    if [[ ! -e "$argv" ]]; then
      mkdir -p "${argv%/*}"
      printf '// %s\n{\n  "disable-hardware-acceleration": true\n}\n' "$MARK" > "$argv"
      log "VS Code GPU 가속 끔: $argv"
    elif ! grep -q '"disable-hardware-acceleration"[[:space:]]*:[[:space:]]*true' "$argv"; then
      warn "$argv 에 \"disable-hardware-acceleration\": true 를 직접 추가하세요 (VS Code 검은 화면 방지)"
    fi
  fi
}

# Pi 의 Chromium 실행 스크립트는 CHROMIUM_FLAGS 를 비운 뒤 /etc/chromium.d/* 를 읽는다.
# RDP 세션일 때만 GPU 를 끄는 설정 파일을 둔다. (모니터 로그인에는 영향 없음)
configure_chromium_rdp() {
  [[ -d /etc/chromium.d ]] || { log "Chromium 설정 폴더 없음, 건너뜀"; return 0; }
  local f=/etc/chromium.d/99-rdp-disable-gpu
  if [[ -e "$f" ]] && ! grep -q "$MARK" "$f"; then
    warn "$f 가 이미 있어 건드리지 않습니다"
    return 0
  fi
  printf '# %s : RDP(xrdp) 세션에서는 GPU 를 쓰지 않는다\nif [ -n "${RDP_SESSION_SETUP:-}" ]; then\n  CHROMIUM_FLAGS="$CHROMIUM_FLAGS --disable-gpu"\nfi\n' "$MARK" \
    | sudo tee "$f" >/dev/null
  log "Chromium: RDP 세션에서 GPU 끔 ($f)"
}

