    sudo usermod -aG "$(IFS=,; echo "${groups[*]}")" "$TARGET_USER"
    log "$TARGET_USER 그룹 추가: ${groups[*]}"
  fi
  if getent passwd xrdp >/dev/null && getent group ssl-cert >/dev/null; then
    sudo usermod -aG ssl-cert xrdp
    log "xrdp 사용자를 ssl-cert 그룹에 추가"
  fi
}

