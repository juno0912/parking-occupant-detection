choose_desktop() {
  # 1순위: Raspberry Pi 공식 X11 데스크톱(rpd-x-core).
  #        rpd-common 이 Debian lxpanel 과 충돌하므로, lxpanel 이 남아 있으면 경량 모드로 간다.
  if { is_installed rpd-x-core || pkg_available rpd-x-core; } \
     && ! { is_installed lxpanel && ! is_installed rpd-common; }; then
    DESKTOP_MODE=rpd
    log "데스크톱: Raspberry Pi Desktop (X11, rpd-x-core)"
    return 0
  fi
  DESKTOP_MODE=light
  warn "rpd-x-core 를 쓸 수 없어 경량 데스크톱(openbox + 패널)으로 구성합니다. 메뉴/앱 목록이 제한됩니다."

  # Raspberry Pi 데스크톱(rpd-common)은 Debian 의 lxpanel 과 충돌하고,
  # pcmanfm-pi 는 pcmanfm 과 함께 설치할 수 없다. 그래서 Pi 용 패키지를 우선 쓴다.
  if is_installed lxpanel && ! is_installed rpd-common; then
    PANEL_PKG=lxpanel          # 이미 설치된 Debian 패널을 그대로 사용
  elif is_installed lxpanel-pi || pkg_available lxpanel-pi; then
    PANEL_PKG=lxpanel-pi
  elif is_installed rpd-common; then
    die "rpd-common 이 설치되어 있는데 lxpanel-pi 를 찾을 수 없습니다. (lxpanel 은 rpd-common 과 충돌)"
  else
    PANEL_PKG=lxpanel
  fi
  if is_installed pcmanfm && ! is_installed pcmanfm-pi; then
    FM_PKG=pcmanfm             # 이미 설치된 Debian 파일 관리자를 그대로 사용
  elif is_installed pcmanfm-pi || pkg_available pcmanfm-pi; then
    FM_PKG=pcmanfm-pi
  else
    FM_PKG=pcmanfm
  fi
  log "패널: $PANEL_PKG / 파일 관리자: $FM_PKG"
}

apt_update() {
  step "패키지 목록 갱신"
  sudo apt-get update || die "apt-get update 실패 (네트워크 또는 저장소 설정 확인)"
}

install_packages() {
  choose_desktop

  step "패키지 설치"
  local required want
  if [[ "$DESKTOP_MODE" == rpd ]]; then
    required=(xrdp xorgxrdp "${PKGS_RPD[@]}")
    want=("${PKGS_RDP[@]}" "${PKGS_RPD[@]}" "${PKGS_RPD_OPTIONAL[@]}" "${PKGS_EXTRA[@]}" "${PKGS_APPS[@]}")
  else
    required=(xrdp xorgxrdp openbox "$PANEL_PKG" "$FM_PKG")
    want=("${PKGS_RDP[@]}" "${PKGS_DESKTOP_BASE[@]}" "$PANEL_PKG" "$FM_PKG" "${PKGS_EXTRA[@]}" "${PKGS_APPS[@]}")
  fi
  local new=() missing=() p
  for p in "${want[@]}"; do
    if is_installed "$p"; then continue; fi
    if pkg_available "$p"; then new+=("$p"); else missing+=("$p"); fi
  done

  for p in "${required[@]}"; do
    if in_list "$p" "${missing[@]+"${missing[@]}"}"; then
      die "필수 패키지를 저장소에서 찾을 수 없습니다: $p"
    fi
  done
  if (( ${#missing[@]} )); then
    warn "저장소에 없어 건너뛴 패키지: ${missing[*]}"
  fi

  # 권장 패키지를 따라 VNC 서버나 첫 부팅 마법사가 새로 들어오지 않게 막는다.
  # (apt 의 "패키지명-" 표기. 이미 설치된 것은 지우지 않도록 미설치일 때만 붙인다)
  local block=()
  for p in realvnc-vnc-server wayvnc piwiz; do
    if ! is_installed "$p" && pkg_available "$p"; then block+=("$p-"); fi
  done

  if (( ${#new[@]} )); then
    log "새로 설치: ${new[*]}"
    apt_install_safe "${new[@]}" "${block[@]+"${block[@]}"}"
    printf '%s\n' "${new[@]}" | sudo tee -a "$STATE_DIR/installed_pkgs" >/dev/null
  else
    log "추가로 설치할 패키지 없음"
  fi
}

