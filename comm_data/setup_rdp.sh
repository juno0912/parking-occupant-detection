# RDP 화면 진단: Pi 의 X 화면을 직접 캡처한다.
#  - 캡처가 정상인데 mstsc 화면만 깨지면 → 전송(mstsc/xrdp 설정) 문제
#  - 캡처도 검으면 → Pi 쪽 데스크톱 그리기 문제
diag_screen() {
  step "RDP 화면 진단"
  local d out="$TARGET_HOME/rdp_screen.png"
  d="$(ls /tmp/.X11-unix 2>/dev/null | grep -E '^X1[0-9]+$' | sort -V | tail -n 1 || true)"
  [[ -n "$d" ]] || die "실행 중인 RDP(Xorg) 화면이 없습니다. mstsc 로 접속해 둔 상태에서 실행하세요."
  export DISPLAY=":${d#X}" XAUTHORITY="$TARGET_HOME/.Xauthority"
  log "디스플레이: $DISPLAY"
  log "--- 모니터"; xrandr --listmonitors 2>&1 || true
  if python3 - "$out" <<'PY'
import os, sys
from PIL import ImageGrab
ImageGrab.grab(xdisplay=os.environ["DISPLAY"]).save(sys.argv[1])
PY
  then
    log "[OK] Pi 화면 캡처 저장: $out"
  else
    warn "화면 캡처 실패 (위 오류 확인)"
  fi
  log "--- 실행 중인 데스크톱 프로세스"
  pgrep -a 'lxsession|openbox|lxpanel|pcmanfm|xcompmgr' || true
  log "--- 화면에 떠 있는 창 (이름, 크기+위치)"
  if command -v xwininfo >/dev/null; then
    xwininfo -root -tree 2>/dev/null | grep -E '0x[0-9a-f]+ "[^"]+".*[0-9]+x[0-9]+' | head -n 40 || true
  else
    warn "xwininfo 없음 (sudo apt install x11-utils)"
  fi
  log "--- 큰 창 (가로 500px 이상: 바탕화면/작업표시줄/앱)"
  if command -v xwininfo >/dev/null; then
    xwininfo -root -tree 2>/dev/null | grep -E ' ([5-9][0-9]{2}|[0-9]{4})x[0-9]+\+' | head -n 20 || true
  fi
  log "--- GTK 앱이 보는 모니터 (작업표시줄/바탕화면은 이 값으로 크기를 정함)"
  python3 - <<'PY' 2>&1 || true
import gi
gi.require_version("Gdk", "3.0")
from gi.repository import Gdk
d = Gdk.Display.get_default()
n = d.get_n_monitors()
print("monitors:", n)
for i in range(n):
    m = d.get_monitor(i); g = m.get_geometry(); w = m.get_workarea()
    print(i, m.get_model(), "geometry", g.x, g.y, g.width, g.height,
          "workarea", w.x, w.y, w.width, w.height, "scale", m.get_scale_factor(),
          "primary", m.is_primary())
s = Gdk.Screen.get_default()
print("screen", s.get_width(), "x", s.get_height())
PY
  log "--- openbox 경고"
  grep -m 3 'Unable' "$TARGET_HOME/.cache/lxsession/rpd-x/run.log" 2>/dev/null || true
  log "--- 바탕화면 설정"
  local c
  for c in "$TARGET_HOME"/.config/pcmanfm/*/desktop-items-0.conf /etc/xdg/pcmanfm/default/desktop-items-0.conf; do
    [[ -f "$c" ]] || continue
    log "[$c]"; grep -E '^(wallpaper_mode|wallpaper|desktop_bg)=' "$c" || true
    break
  done
  local wp; wp="$(grep -hE '^wallpaper=' "$TARGET_HOME"/.config/pcmanfm/*/desktop-items-0.conf /etc/xdg/pcmanfm/default/desktop-items-0.conf 2>/dev/null | head -n 1 | cut -d= -f2- || true)"
  if [[ -n "$wp" ]]; then
    if [[ -f "$wp" ]]; then log "[OK] 배경 파일 있음: $wp"; else warn "배경 파일 없음: $wp"; fi
  fi
  log "--- 이미지 로더"
  local lc; lc="$(compgen -G '/usr/lib/*/gdk-pixbuf-2.0/2.10.0/loaders.cache' | head -n 1 || true)"
  if [[ -n "$lc" ]]; then grep -oE '"[^"]*/loaders/[^"]*\.so"' "$lc" | sed 's#.*/##; s#"##' | tr '\n' ' '; echo; else warn "loaders.cache 없음"; fi
  log "--- 세션 로그 (마지막 15줄)"
  tail -n 15 "$TARGET_HOME/.cache/lxsession/rpd-x/run.log" 2>/dev/null || true
}

# -----------------------------------------------------------------------------
rollback() {
  step "되돌리기"
  [[ -f "$STATE_DIR/manifest" ]] || die "복구 기록($STATE_DIR/manifest)이 없습니다. 이 스크립트로 설치한 Pi 가 아니므로 아무것도 바꾸지 않습니다."

  # 1) 패키지: 이 스크립트가 새로 설치한 RDP/데스크톱 패키지만 제거
  local rm_list=() p
  if [[ -s "$STATE_DIR/installed_pkgs" ]]; then
    while IFS= read -r p; do
      [[ -z "$p" ]] && continue
      if ! in_list "$p" "${PKGS_KEEP[@]}" && is_installed "$p"; then rm_list+=("$p"); fi
    done < <(sort -u "$STATE_DIR/installed_pkgs")
  fi
  local incomplete=0
  if (( ${#rm_list[@]} )); then
    log "제거 대상: ${rm_list[*]}"
    if ! safe_purge "${rm_list[@]}"; then
      warn "패키지는 남겨 두었습니다."
      incomplete=1
    fi
  fi
  log "폰트/카메라/파이썬 패키지는 남겨 둡니다. VNC 는 다시 설치하지 않습니다."

  # 2) xrdp 가 원래 있었다면 원래 활성 상태로
  if is_installed xrdp; then
    if [[ "$(state_get xrdp_prev_enabled)" == "enabled" ]]; then
      log "xrdp 는 원래 활성 상태였으므로 그대로 둡니다."
    else
      sudo systemctl disable --now xrdp xrdp-sesman 2>/dev/null || true
      log "xrdp 비활성화"
    fi
  fi

  # 3) 시작 파일: 이 스크립트가 만든 것일 때만 삭제하고 백업 복원
  local xs bak
  xs="$(state_get session_file)"
  if [[ -n "$xs" && -f "$xs" && ! -L "$xs" ]] && grep -q "$MARK" "$xs"; then
    rm -f "$xs"
    log "삭제: $xs"
  elif [[ -n "$xs" && -e "$xs" ]]; then
    warn "$xs 가 수정되어 있어 그대로 둡니다."
  fi
  bak="$(state_get session_backup)"
  if [[ -n "$bak" && -f "$bak" && -n "$xs" && ! -e "$xs" ]]; then
    mv "$bak" "$xs"
    log "복원: $xs"
  fi

  local f
  for f in "$TARGET_HOME/.local/bin/rdp-xcompmgr" "$TARGET_HOME/.local/bin/rdp-panel-fix" \
           "$TARGET_HOME/.config/autostart/xcompmgr.desktop" "$TARGET_HOME/.config/autostart/rdp-panel-fix.desktop" \
           "$TARGET_HOME/.vscode/argv.json"; do
    if [[ -f "$f" ]] && grep -q "$MARK" "$f"; then rm -f "$f"; log "삭제: $f"; fi
  done
  if [[ -f /etc/chromium.d/99-rdp-disable-gpu ]] && grep -q "$MARK" /etc/chromium.d/99-rdp-disable-gpu; then
    sudo rm -f /etc/chromium.d/99-rdp-disable-gpu
    log "삭제: /etc/chromium.d/99-rdp-disable-gpu"
  fi

  # 바로가기 실행 확인 창 설정(quick_exec) 원래 값으로
  local qprev; qprev="$(state_get quick_exec_prev)"
  if [[ -n "$qprev" && -f "$TARGET_HOME/.config/libfm/libfm.conf" ]]; then
    set_ini_key "$TARGET_HOME/.config/libfm/libfm.conf" config quick_exec "$([[ "$qprev" == unset ]] && echo 0 || echo "$qprev")"
    log "바로가기 실행 확인 창 설정 복원"
  fi

  local orc; orc="$(state_get openbox_rc)"
  if [[ -n "$orc" && -f "$orc" ]] && grep -q "$MARK" "$orc"; then
    rm -f "$orc"
    log "삭제: $orc"
  fi

  # 4) 부팅 모드 (자동 로그인은 복원하지 않음)
  local prev; prev="$(state_get default_target)"
  if [[ "$prev" == "graphical.target" ]]; then
    if command -v raspi-config >/dev/null; then
      sudo raspi-config nonint do_boot_behaviour B3
    else
      sudo systemctl set-default graphical.target
    fi
  elif [[ -n "$prev" ]]; then
    sudo systemctl set-default "$prev"
  fi
  log "기본 부팅 대상: $(systemctl get-default) (자동 로그인은 꺼진 상태로 둡니다)"

  if (( incomplete )); then
    warn "일부 패키지를 제거하지 못해 복구 기록($STATE_DIR)은 남겨 둡니다. 원인 해결 후 --rollback 을 다시 실행하세요."
  else
    sudo rm -rf "$STATE_DIR"
  fi
  log "되돌리기 완료. 재부팅하세요: sudo reboot"
}

# -----------------------------------------------------------------------------
main() {
  case "$MODE" in
    -h|--help) usage; exit 0 ;;
  esac
  # sudo 로 실행하면 root 홈에 로그/설정이 생기므로 가장 먼저 막는다
  if [[ $EUID -eq 0 ]]; then
    echo "[오류] 'sudo bash setup_rdp.sh' 가 아니라 'bash setup_rdp.sh' 로 일반 사용자가 실행하세요." >&2
    exit 1
  fi
  case "$MODE" in
    --check|check) MODE=--check; check || exit 1; exit 0 ;;
    --fix-logout)  configure_panel_logout; log "RDP 세션에서 로그아웃 후 다시 접속하면 적용됩니다."; exit 0 ;;
    --user-config) configure_user_desktop; log "RDP 세션에서 로그아웃 후 다시 접속하면 적용됩니다."; exit 0 ;;
    --screenshot)  diag_screen; exit 0 ;;
    install|--rollback|rollback|--purge-vnc) ;;
    *) usage; exit 1 ;;
  esac
  [[ "$MODE" == rollback ]] && MODE=--rollback

  : >>"$LOG" || { echo "로그 파일을 만들 수 없습니다: $LOG" >&2; exit 1; }
  exec > >(tee -a "$LOG") 2>&1
  log "로그 파일: $LOG"

  preflight_common
  if [[ "$MODE" == --rollback ]]; then
    rollback
    exit 0
  fi
  if [[ "$MODE" == --purge-vnc ]]; then
    systemctl is-active --quiet xrdp || die "xrdp 가 실행 중이 아니어서 VNC 를 지우지 않습니다."
    remove_vnc
    exit 0
  fi

  preflight_install
  apt_update            # 저장소 목록을 먼저 갱신해야 이전 버전 정리/데스크톱 선택이 정확하다
  migrate_legacy
  install_packages
  configure_session
  configure_user_desktop
  configure_chromium_rdp
  configure_groups
  configure_boot
  enable_xrdp
  if ! check; then
    warn "점검에서 문제가 발견되었습니다. 위 [경고]를 확인하세요."
  fi
  step "완료"
  log "1) 재부팅:  sudo reboot"
  log "2) Windows: Win+R → mstsc → $(hostname -I | awk '{print $1}') → '$TARGET_USER' 로 로그인"
  log "3) RDP 화면에서 Ctrl+Alt+T 로 터미널 → 카메라 미리보기: rpicam-hello -t 0 --qt-preview"
  log "4) 끝낼 때는 창 닫기 말고 로그아웃"
}

main
