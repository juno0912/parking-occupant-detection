preflight_common() {
  [[ $EUID -ne 0 ]] || die "root 가 아니라 일반 사용자로 실행하세요. sudo 는 스크립트가 직접 씁니다."
  [[ -n "$TARGET_HOME" && -d "$TARGET_HOME" ]] || die "사용자 홈 디렉터리를 찾을 수 없습니다: $TARGET_USER"
  sudo -v || die "sudo 권한을 확인할 수 없습니다."
  # 출력을 /dev/null 로 돌려 로그(tee) 파이프를 붙잡지 않게 한다
  ( while kill -0 "$$" 2>/dev/null; do sudo -n -v 2>/dev/null || break; sleep 50; done ) >/dev/null 2>&1 &
  SUDO_KEEPALIVE=$!
}

preflight_install() {
  step "사전 점검"
  local arch; arch="$(uname -m)"
  [[ "$arch" == "aarch64" ]] || warn "아키텍처가 aarch64 가 아닙니다: $arch"

  # shellcheck disable=SC1091
  . /etc/os-release
  log "OS: ${PRETTY_NAME:-unknown} / 사용자: $TARGET_USER"
  [[ "${VERSION_CODENAME:-}" == "trixie" ]] || warn "trixie 기준으로 작성되었습니다. 현재: ${VERSION_CODENAME:-unknown}"

  local free_mb; free_mb="$(df -Pm / | awk 'NR==2{print $4}')"
  log "루트 여유 공간: ${free_mb}MB"
  (( free_mb > 1500 )) || die "여유 공간이 1.5GB 미만입니다."

  sudo mkdir -p "$STATE_DIR"
  state_set_once manifest "created $(date -Is) by $TARGET_USER"
  state_set_once default_target "$(systemctl get-default)"
  if is_installed xrdp; then
    state_set_once xrdp_prev_enabled "$(systemctl is-enabled xrdp 2>/dev/null || true)"
  else
    state_set_once xrdp_prev_enabled "not-installed"
  fi
}

