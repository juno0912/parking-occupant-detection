user_wm_file() {
  # xrdp 가 사용자 홈에서 찾는 시작 파일 이름 (sesman.ini 의 UserWindowManager, 기본 startwm.sh)
  local ini=/etc/xrdp/sesman.ini name=""
  if [[ -f "$ini" ]]; then
    name="$(awk -F= 'tolower($1) ~ /^[ \t]*userwindowmanager[ \t]*$/ {gsub(/[ \t\r]/,"",$2); print $2; exit}' "$ini")"
  fi
  printf '%s\n' "${name:-startwm.sh}"
}

configure_session() {
  step "RDP 세션 구성"
  local ini=/etc/xrdp/sesman.ini
  if [[ -f "$ini" ]] && grep -qiE '^[[:space:]]*EnableUserWindowManager[[:space:]]*=[[:space:]]*(false|no|0)' "$ini"; then
    die "sesman.ini 에서 EnableUserWindowManager 가 꺼져 있어 RDP 시작 파일이 무시됩니다. $ini 에서 true 로 바꾼 뒤 다시 실행하세요."
  fi

  local xs; xs="$TARGET_HOME/$(user_wm_file)"
  [[ ! -L "$xs" ]] || die "$xs 가 심볼릭 링크입니다. 덮어쓰지 않고 중단합니다. 직접 확인하세요."
  if [[ -f "$xs" ]] && ! grep -q "$MARK" "$xs"; then
    local bak; bak="$xs.bak.$(date +%Y%m%d_%H%M%S)"
    cp -a "$xs" "$bak"
    state_set_once session_backup "$bak"
    log "기존 시작 파일 백업: $bak"
  fi
  state_set_once session_file "$xs"

  local tmp; tmp="$(mktemp "$xs.tmp.XXXXXX")"
  cat > "$tmp" <<EOF
#!/bin/sh
# $MARK : xrdp(X11) 세션 전용 시작 파일 (Pi 로컬 데스크톱 로그인에는 영향 없음)
unset WAYLAND_DISPLAY
export XDG_SESSION_TYPE=x11
export GDK_BACKEND=x11
export QT_QPA_PLATFORM=xcb
# RDP 세션 표시 (자동 시작 항목이 RDP 인지 구분하는 데 사용)
export RDP_SESSION_SETUP=1
# xrdp 에는 GPU 가속이 없다. GPU 를 쓰려는 앱이 검은 창이 되지 않도록 소프트웨어 렌더링 사용
# (Chromium 은 실행 스크립트가 CHROMIUM_FLAGS 를 비우므로 /etc/chromium.d/ 에서 따로 처리)
export LIBGL_ALWAYS_SOFTWARE=1

# 세션 D-Bus 가 없으면 하나 만들고 그 안에서 다시 시작 (패널/파일관리자/openbox 가 같은 버스 사용)
if [ -z "\$DBUS_SESSION_BUS_ADDRESS" ] && [ -z "\$RDP_SESSION_BUS" ] && command -v dbus-run-session >/dev/null 2>&1; then
  RDP_SESSION_BUS=1 exec dbus-run-session -- /bin/sh "\$0"
fi

# Raspberry Pi 공식 X11 데스크톱 (메뉴, 앱 목록, 시계, 로그아웃)
if [ -x /usr/bin/startx-rpd ]; then
  exec /usr/bin/startx-rpd
fi

# 대체: 경량 데스크톱
if command -v lxpanel-pi >/dev/null 2>&1; then lxpanel-pi &
elif command -v lxpanel >/dev/null 2>&1; then lxpanel &
fi
if command -v pcmanfm >/dev/null 2>&1; then pcmanfm --desktop &
elif command -v pcmanfm-pi >/dev/null 2>&1; then pcmanfm-pi --desktop &
fi
exec openbox-session
EOF
  chmod 755 "$tmp"
  mv -f "$tmp" "$xs"
  log "작성 완료: $xs"

  # 공식 데스크톱은 단축키/로그아웃을 자체 설정(lxsession, rpd-rc.xml)으로 처리한다.
  if [[ "$DESKTOP_MODE" == light ]]; then
    configure_openbox_keys
    configure_panel_logout
  fi
}

# lxsession 없이 openbox 로 세션을 띄우면 패널의 Logout 이 "Logout command is not set" 오류를 낸다.
# 패널 설정의 [Command] Logout 을 openbox --exit 로 지정한다. (lxpanel / lxpanel-pi 둘 다)
configure_panel_logout() {
  local base sys usr done_any=0
  for base in lxpanel lxpanel-pi; do
    sys="/etc/xdg/$base/default/config"
    usr="$TARGET_HOME/.config/$base/default/config"
    [[ -f "$sys" || -f "$usr" ]] || continue
    if [[ ! -f "$usr" ]]; then
      mkdir -p "${usr%/*}"
      cp "$sys" "$usr"
    fi
    set_ini_key "$usr" Command Logout "openbox --exit"
    log "패널 로그아웃 명령 설정: $usr"
    done_any=1
  done
  (( done_any )) || warn "lxpanel 설정 파일을 찾지 못해 로그아웃 명령을 설정하지 않았습니다"
  return 0
}

# 바탕화면 오른쪽 클릭은 pcmanfm 이 가져가므로 Ctrl+Alt+T 로 터미널을 열 수 있게 한다.
configure_openbox_keys() {
  local rc="$TARGET_HOME/.config/openbox/rc.xml"
  if [[ -f "$rc" ]]; then
    if grep -q "$MARK" "$rc"; then log "Ctrl+Alt+T 단축키 이미 설정됨"; else warn "기존 $rc 가 있어 단축키를 추가하지 않습니다"; fi
    return 0
  fi
  if [[ ! -f /etc/xdg/openbox/rc.xml ]]; then
    warn "openbox 기본 설정(/etc/xdg/openbox/rc.xml)이 없어 단축키를 추가하지 않습니다"
    return 0
  fi
  mkdir -p "${rc%/*}"
  sed "0,/<keyboard>/s#<keyboard>#<keyboard>\n    <!-- $MARK -->\n    <keybind key=\"C-A-t\"><action name=\"Execute\"><command>lxterminal</command></action></keybind>#" \
    /etc/xdg/openbox/rc.xml > "$rc"
  state_set_once openbox_rc "$rc"
  log "Ctrl+Alt+T = 터미널 단축키 추가: $rc"
}

