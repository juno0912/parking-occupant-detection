enable_xrdp() {
  step "xrdp 서비스 활성화 및 확인"
  sudo systemctl enable xrdp
  sudo systemctl restart xrdp
  local i
  for i in 1 2 3 4 5; do
    if systemctl is-active --quiet xrdp && port_listening 3389; then
      log "[OK] xrdp 실행 중, 3389 포트 대기 중"
      return 0
    fi
    sleep 2
  done
  die "xrdp 가 시작되지 않았습니다. 'sudo journalctl -u xrdp -u xrdp-sesman -n 50' 확인. (VNC 는 그대로 두었습니다)"
}

port_listening() {
  local listen; listen="$(ss -ltnH 2>/dev/null | awk '{print $4}' || true)"
  grep -qE "(^|:)$1\$" <<<"$listen"
}

