remove_vnc() {
  step "VNC 정리 (--purge-vnc)"
  local svc out
  for svc in wayvnc vncserver-x11-serviced vncserver-virtuald; do
    out="$(systemctl list-unit-files "${svc}.service" --no-legend 2>/dev/null || true)"
    [[ -n "$out" ]] || continue
    if sudo systemctl disable --now "$svc" 2>/dev/null; then
      log "중지/비활성화: $svc"
    else
      warn "중지 실패: $svc"
    fi
  done

  local to_purge=() p
  for p in wayvnc realvnc-vnc-server; do
    if is_installed "$p"; then to_purge+=("$p"); fi
  done
  if (( ${#to_purge[@]} == 0 )); then
    log "설치된 VNC 패키지 없음"
    return 0
  fi
  safe_purge "${to_purge[@]}" || warn "VNC 패키지는 남겨 두었습니다(서비스는 꺼짐): ${to_purge[*]}"
}

